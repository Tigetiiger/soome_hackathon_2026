def abstract(summary: dict | None, metrics: dict | None) -> str:
    n_mach = dig(metrics, "compute", "machines") or (summary or {}).get("n_bins") or "–"
    t = dig(metrics, "splits", "time", "final", "lift", "overall") or {}
    u = dig(metrics, "splits", "bins", "final", "lift", "overall") or {}
    return (f'<p class="abstract">This document describes a hydraulic soft sensor that estimates the mass of waste inside '
            "a press-container compactor every hour, using only signals the machine already produces — the firmware "
            "fill reading, press counts, peak ram pressure, the per-stroke pressure graph and oil temperature — "
            f"together with public weather data. Gradient-boosted tree models (LightGBM) are trained on a physics-based "
            f"simulation of {escape(str(n_mach))} machines over one year. Evaluated in the hour before each lift against the "
            f"true container mass, the selected model reaches a mean error of {num(t.get('mean_pct'))} % on the same machines "
            f"in later months and {num(u.get('mean_pct'))} % on machines it has never seen, against "
            f"{num(dig(metrics, 'splits', 'bins', 'ladder', 'naive_fill_x_density', 'overall', 'mean_pct'))} % for the naive "
            "fill × density estimate. A calibrated p10–p90 interval accompanies every estimate. Sections 2–4 document the "
            "model, Section 5 the simulator that generated the data, Sections 6–8 limitations, downloads and a glossary.</p>"
            '<p class="notice"><strong>All data in this document is synthetic.</strong> It was generated by the simulator '
            "described in Section 5. No number here is a measurement from a real Europress machine, and the hydraulic "
            "parameters of the simulator are assumptions, not real Europress settings. The results demonstrate the method, "
            "not field performance.</p>")


def flow() -> str:
    boxes = [
        ("Raw device signals per hour", ["fill reading, presses, peak pressure, oil temperature, energy",
                                         "pressure-graph features", "machine configuration", "public weather"]),
        ("Feature engineering", ["per machine, backward-looking only", "cycle = since the last emptying",
                                 "completed days for daily weather", f"{len(FEATURE_SETS['full'])} features (full set)"]),
        ("LightGBM", ["target = kg per m³ of container", "shared versus per-material model, chosen on validation",
                      "p10 / p90 quantile models", "conformal calibration → 80 % interval"]),
        ("Output per hour", ["mass_pred_kg = kg/m³ × volume", "mass_p10_kg, mass_p90_kg",
                             "value in the pre-lift hour ↔ weighbridge"]),
    ]
    html = []
    for i, (title, items) in enumerate(boxes):
        if i:
            html.append('<div class="arrow" aria-hidden="true">→</div>')
        html.append(f'<div class="box"><b>{escape(title)}</b><ul>' + "".join(f"<li>{escape(t)}</li>" for t in items) + "</ul></div>")
    return '<div class="flow">' + "".join(html) + "</div>"


def what(metrics: dict | None) -> str:
    return (h3("What is estimated", "ov-what")
            + p("The quantity of interest is the mass of waste in the container, in kg, at the end of every hour. The model "
                "predicts mass per m³ of container (the kg/m³ target) and multiplies back by the container volume, so one "
                "model covers all container sizes. The number a customer cares about is the estimate in the pre-lift hour: "
                "the last hour before the container is emptied, which is the mass the transporter's weighbridge later "
                "reports. Every hourly estimate comes with a p10–p90 interval.")
            + p("The machine does not have a level sensor. Its fill reading is a firmware estimate derived from a rolling "
                "average of back pressure, and it says little about weight: the same fill can hold a light or a heavy pack. "
                "The peak pressure, the shape of the pressure graph along the stroke and the number of presses since the "
                "last lift carry the information about density that the fill reading lacks; weather matters through the "
                "moisture of fibre materials and through cold hydraulic oil.") + flow())


def data(summary: dict | None, cfg: dict | None, metrics: dict | None) -> str:
    if not summary:
        return h3("Data", "ov-data") + p("Simulation summary not available at build time.")
    start = pd.Timestamp(summary.get("start") or dig(cfg, "run", "start"))
    end = start + pd.Timedelta(days=int(summary.get("days", 365)) - 1)
    lm = summary.get("lift_mass_by_material") or {}
    mats = ", ".join(f"{m} {num(x.get('count'), 0)}" for m, x in lm.items())
    rows = [["machines (one site each)", num(summary.get("n_bins"), 0)],
            ["reported period", f"{start:%Y-%m-%d} to {end:%Y-%m-%d} ({summary.get('days')} days), after a 28-day burn-in"],
            ["hourly rows", num(summary.get("hourly_rows"), 0)], ["lifts", f"{num(summary.get('n_lifts'), 0)} ({mats})"],
            ["materials", ", ".join(f"{m} {num(x * 100, 0)} %" for m, x in (dig(cfg, "fleet", "material_shares") or {}).items())],
            ["weather regions", ", ".join((dig(cfg, "weather", "regions") or {}).keys()) or "–"],
            ["share of lifts triggered by a false-full reading", f"{pct_of(summary.get('false_full_lift_share'))} %"],
            ["random seed", str(summary.get("seed"))]]
    return (h3("Data", "ov-data")
            + p("All training and test data come from one simulation run (Section 5). The run writes hourly telemetry "
                "as a real machine would report it, plus the hidden truth used only for evaluation.")
            + table(["item", "value"], rows, caption="The simulation run used for training and evaluation.", left_cols={0, 1}))


def protocol(metrics: dict | None) -> str:
    rows = []
    for split in ("time", "bins"):
        sp = dig(metrics, "splits", split) or {}
        r = sp.get("rows") or {}
        rows.append([f"<strong>{escape(SPLIT_LABEL[split])}</strong>", escape(SPLITS[SPLIT_LABEL[split]].split(":", 1)[1].split(";")[-1].strip()),
                     escape(str(sp.get("n_train_machines", "–"))), escape(str(sp.get("n_test_machines", "–"))),
                     escape(str(sp.get("test_start", "–"))[:10])]
                    + [num(r.get(k), 0) for k in ("train", "val", "cal", "test")])
    return (h3("Evaluation protocol", "ov-protocol")
            + p("Two splits are reported. <strong>Same machines, later months</strong> is the pilot-fleet case: every machine "
                "is in the training data, and the model is tested on the later part of the year. <strong>Unseen machines</strong> "
                "is the new-installation case: a quarter of the machines, stratified by material, are held out entirely and "
                "tested on the later part of the year. In both splits the validation slice (tuning, early stopping, shared "
                "versus per-material choice) and the calibration slice (interval width) are taken from rows that are neither "
                "trained on nor tested; in the unseen-machines split they are other held-out machines. The first, incomplete "
                "cycle of every machine is excluded everywhere.")
            + raw_table(["split", "case", "train machines", "test machines", "test from", "rows: train", "val", "cal", "test"],
                        rows, left_cols={0, 1}, caption="The two evaluation splits.")
            + p("Training rows are every pre-lift hour plus a random sample of other hours (at most 200 000 rows per model); "
                "pre-lift hours carry weight 5 because they are the hours that are compared with the weighbridge. All "
                "training is CPU-only and deterministic."))


def notation() -> str:
    order = ["mean % error", "median % error", "within 5 %", "within 10 %", "MAE", "bias", "p10", "p90", "p10–p90 interval",
             "coverage", "width", "pp"]
    rows = [[f"<strong>{escape(k)}</strong>", escape(METRICS[k])] for k in order]
    return (h3("Metrics and notation", "ov-metrics")
            + p("Unless stated otherwise, a metric is computed over the pre-lift hours of the test split (one value per lift) "
                "and compares the model estimate with the true container mass of the simulator. 'Hourly' metrics use every "
                "test hour instead. Percentage errors are relative to the true mass and exclude lifts below 200 kg, where a "
                f"percentage is meaningless (near-empty false-full lifts). Table cells under {GOOD_PCT:.0f} % — the hackathon "
                "target for the mean error at lift — are shaded in the result tables.")
            + raw_table(["metric", "definition"], rows, left_cols={0, 1}, caption="Metrics used in this document."))


def ladder_def() -> str:
    rows = []
    for step, desc in LADDER_STEPS.items():
        fs = LADDER_SETS[step]
        nfeat = "–" if fs == "—" else str(len(FEATURE_SETS[fs]))
        rows.append([term(step, step.replace(" (ladder step)", "")), escape(desc.split(":", 1)[1].strip()), escape(fs), nfeat])
    return (h3("The comparison ladder", "ov-ladder")
            + p("To show what each signal contributes, the same test lifts are evaluated with models that add one feature "
                "family at a time. Step 0 is not a model at all but the formula a customer could apply by hand. The feature "
                "sets are listed in Section 2.3; results are in Section 3.2.")
            + raw_table(["step", "what it is", "feature set", "features"], rows, left_cols={0, 1, 2},
                        caption="Steps of the comparison ladder."))


def headline(metrics: dict | None, figs: list) -> str:
    rows = []
    for split in ("time", "bins"):
        sp = dig(metrics, "splits", split) or {}
        g = dig(sp, "final", "lift", "overall") or {}
        naive = dig(sp, "ladder", "naive_fill_x_density", "overall", "mean_pct")
        hourly = dig(sp, "final", "hourly", "overall", "mean_pct")
        rows.append([SPLIT_LABEL[split], num(g.get("n"), 0), num(g.get("mean_pct")), num(g.get("median_pct")),
                     pct_of(g.get("within_5pct"), 0), num(g.get("mae_kg"), 0), num(g.get("bias_kg"), 0),
                     pct_of(g.get("coverage"), 0), num(g.get("width_kg"), 0), num(hourly), num(naive)])
    head = ["split", "lifts", "mean %", "median %", "within 5 % (%)", "MAE kg", "bias kg", "coverage %", "width kg",
            "hourly mean %", "naive fill × density mean %"]
    return (h3("Headline results", "ov-results")
            + p("Selected model (shared or per-material per material, chosen on validation), evaluated in the pre-lift hour. "
                "The last column is ladder step 0 on the same lifts. Per-material tables, breakdowns and plots follow in Section 3.")
            + table(head, rows, good_cols={2, 3}, caption="Error at lift of the selected soft sensor on both splits.")
            + figures(figs, single=True))


def overview(b: Build, metrics: dict | None, summary: dict | None, cfg: dict | None, figs: list) -> str:
    return ('<section id="sec-overview" class="doc-head">' + h2("Overview and methods", "overview") + abstract(summary, metrics)
            + what(metrics) + data(summary, cfg, metrics) + protocol(metrics) + notation() + ladder_def()
            + headline(metrics, figs) + "</section>")
